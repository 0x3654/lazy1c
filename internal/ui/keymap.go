package ui

// ruToEn — соответствие букв ЙЦУКЕН → QWERTY по физическим клавишам.
// Горячие клавиши работают в любой раскладке: «в» = d, «к» = r и т.д.
var ruToEn = map[rune]rune{
	'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u', 'ш': 'i', 'щ': 'o', 'з': 'p',
	'ф': 'a', 'ы': 's', 'в': 'd', 'а': 'f', 'п': 'g', 'р': 'h', 'о': 'j', 'л': 'k', 'д': 'l',
	'я': 'z', 'ч': 'x', 'с': 'c', 'м': 'v', 'и': 'b', 'т': 'n', 'ь': 'm',
	'Й': 'Q', 'Ц': 'W', 'У': 'E', 'К': 'R', 'Е': 'T', 'Н': 'Y', 'Г': 'U', 'Ш': 'I', 'Щ': 'O', 'З': 'P',
	'Ф': 'A', 'Ы': 'S', 'В': 'D', 'А': 'F', 'П': 'G', 'Р': 'H', 'О': 'J', 'Л': 'K', 'Д': 'L',
	'Я': 'Z', 'Ч': 'X', 'С': 'C', 'М': 'V', 'И': 'B', 'Т': 'N', 'Ь': 'M',
}

// keyNorm — привести одиночную букву к латинице по физической клавише.
// Применяется только к командным клавишам; ввод текста (фильтр, форма)
// не переводится — там важны настоящие символы.
func keyNorm(s string) string {
	r := []rune(s)
	if len(r) != 1 {
		return s
	}
	if en, ok := ruToEn[r[0]]; ok {
		return string(en)
	}
	return s
}
